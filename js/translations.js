function getLanguage() {
  let lang = localStorage.getItem("openfit-lang");
  if (!lang) {
    lang = navigator.language && navigator.language.startsWith("pt") ? "pt" : "en";
  }
  return lang;
}

function setLanguage(lang) {
  localStorage.setItem("openfit-lang", lang);
  applyTranslations(lang);
  updateToggleButton(lang);
  document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
}

function applyTranslations(lang) {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[key] && translations[key][lang]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (el.getAttribute("data-i18n-type") === "placeholder") {
          el.placeholder = translations[key][lang];
        }
      } else if (el.tagName === "OPTION" || el.tagName === "TITLE") {
        el.textContent = translations[key][lang];
      } else if (el.tagName === "LABEL") {
        el.textContent = translations[key][lang];
      } else {
        el.innerHTML = translations[key][lang];
      }
    }
  });
}

function updateToggleButton(lang) {
  const btn = document.getElementById("lang-toggle");
  if (btn) {
    btn.textContent = lang === "en" ? "PT" : "EN";
    btn.setAttribute("data-active-lang", lang);
  }
}

function toggleLanguage() {
  const current = getLanguage();
  const next = current === "en" ? "pt" : "en";
  setLanguage(next);
}

document.addEventListener("DOMContentLoaded", () => {
  const initialLang = getLanguage();
  setLanguage(initialLang);

  const menuIcon = document.querySelector(".menu-icon");
  const navUl = document.querySelector("nav ul");
  if (menuIcon && navUl) {
    menuIcon.addEventListener("click", () => {
      navUl.classList.toggle("active");
    });
    document.addEventListener("click", (e) => {
      if (!e.target.closest("nav")) {
        navUl.classList.remove("active");
      }
    });
  }
});
